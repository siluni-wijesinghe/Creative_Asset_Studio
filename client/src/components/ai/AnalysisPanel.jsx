// "unknown" (any capitalization) or empty means the AI couldn't tell
const isUnknown = (value) => !value || value.toLowerCase() === "unknown";

function confidenceLabel(confidence) {
  if (confidence >= 0.8) return "High";
  if (confidence >= 0.5) return "Medium";
  return "Low";
}

// A row of small pills
function Chips({ items }) {
  if (items.length === 0) {
    return <span className="text-sm text-stone-400">None found</span>;
  }
  return (
    <div className="flex flex-wrap gap-1.5">
      {items.map((item) => (
        <span key={item} className="rounded-full bg-stone-100 px-2.5 py-1 text-xs text-stone-700">
          {item}
        </span>
      ))}
    </div>
  );
}

// A label with some content under it
function Row({ label, children }) {
  return (
    <div className="mb-4">
      <p className="mb-1.5 text-[13px] text-stone-500">{label}</p>
      {children}
    </div>
  );
}

// A single fact. Missing facts show as a muted "Unknown", never as a guess.
function Fact({ label, value, byUser }) {
  const unknown = isUnknown(value);
  return (
    <div>
      <p className="mb-0.5 text-[13px] text-stone-500">{label}</p>
      <p className={`text-sm ${unknown ? "text-stone-400" : "font-semibold"}`}>
        {unknown ? "Unknown" : value}
        {byUser && !unknown && (
          <span className="ml-1.5 text-xs font-normal text-stone-400">(you provided)</span>
        )}
      </p>
    </div>
  );
}

// Shows what the AI found. Read-only for now.
function AnalysisPanel({ analysis }) {
  const percent = Math.round(analysis.confidence * 100);

  return (
    <div className="mt-3 rounded-2xl border-[1.5px] border-stone-200 bg-white p-4">
      {!analysis.isProduct && (
        <p className="mb-4 rounded-xl bg-amber-50 px-4 py-3 text-sm text-amber-800">
          This doesn't look like a product photo, so these results may not be useful.
        </p>
      )}

      <h3 className="text-base font-semibold">
        {isUnknown(analysis.productName) ? "Unknown product" : analysis.productName}
        {analysis.userProvided.productName && !isUnknown(analysis.productName) && (
          <span className="ml-1.5 text-xs font-normal text-stone-400">(you provided)</span>
        )}
      </h3>
      <p className="mb-4 text-sm text-stone-500">
        {isUnknown(analysis.category) ? "Category unknown" : analysis.category}
      </p>

      <p className="mb-4 text-sm">{analysis.summary}</p>

      <div className="mb-4 grid gap-3 sm:grid-cols-2">
        <Fact label="Brand" value={analysis.brand} byUser={analysis.userProvided.brand} />
        <Fact label="Material" value={analysis.material} />
      </div>

      <Row label="Visible characteristics">
        <Chips items={analysis.visibleCharacteristics} />
      </Row>
      <Row label="Colors">
        <Chips items={analysis.colors} />
      </Row>
      <Row label="Text visible on the product">
        <Chips items={analysis.visibleText} />
      </Row>
      <Row label="Keywords">
        <Chips items={analysis.keywords} />
      </Row>
      <Row label="Tags">
        <Chips items={analysis.tags} />
      </Row>

      {analysis.uncertainties.length > 0 && (
        <Row label="What the AI couldn't tell">
          <ul className="list-disc pl-5 text-sm text-stone-600">
            {analysis.uncertainties.map((item) => (
              <li key={item}>{item}</li>
            ))}
          </ul>
        </Row>
      )}

      {/* The model's own estimate. A guide, not a guarantee. */}
      <div className="mb-3">
        <div className="mb-1.5 flex justify-between text-[13px] text-stone-500">
          <span>AI confidence (its own estimate)</span>
          <span>
            {confidenceLabel(analysis.confidence)} · {percent}%
          </span>
        </div>
        <div className="h-1.5 w-full rounded-full bg-stone-100">
          <div className="h-full rounded-full bg-stone-900" style={{ width: `${percent}%` }} />
        </div>
      </div>

      <p className="text-xs text-stone-400">
        Generated by AI from the photo. Check it against the photo before you use it.
      </p>
    </div>
  );
}

export default AnalysisPanel;